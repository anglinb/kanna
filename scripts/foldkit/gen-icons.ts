#!/usr/bin/env bun
// Writes src/foldkit/ui/icons.ts: one Foldkit icon per lucide-react icon the
// React client imports, rendering the same <svg> lucide-react does (same
// classes, attributes and paths, from the vanilla `lucide` package of the
// same version). Rerun after porting code that uses a new icon; once React is
// gone, add new icons to icons.ts by hand in the same form.

import { readFileSync, writeFileSync } from "node:fs"
import path from "node:path"

const ROOT = path.resolve(import.meta.dirname, "../..")
const reactIndex = readFileSync(path.join(ROOT, "node_modules/lucide-react/dist/esm/lucide-react.js"), "utf8")
const vanillaIndex = readFileSync(path.join(ROOT, "node_modules/lucide/dist/esm/lucide.js"), "utf8")

// export name → icon file name, e.g. Loader2 → loader-circle
function exportsByName(index: string) {
  const names = new Map<string, string>()
  for (const match of index.matchAll(/export \{([^}]*)\} from '\.\/icons\/([\w-]+)\.js'/g)) {
    for (const part of match[1]!.split(",")) {
      const name = /default as (\w+)/.exec(part)?.[1]
      if (name) names.set(name, match[2]!)
    }
  }
  return names
}
const reactNames = exportsByName(reactIndex)
const vanillaNames = exportsByName(vanillaIndex)
const vanillaByFile = new Map<string, string>()
for (const [name, file] of vanillaNames) if (!vanillaByFile.has(file) || name.length < vanillaByFile.get(file)!.length) vanillaByFile.set(file, name)

const used = new Set<string>()
const files = Bun.spawnSync(["git", "ls-files", "src/client", "src/foldkit"], { cwd: ROOT }).stdout.toString().split("\n").filter((f) => /\.(tsx?|ts)$/.test(f))
for (const file of files) {
  const source = readFileSync(path.join(ROOT, file), "utf8")
  for (const match of source.matchAll(/import\s*(?:type\s*)?\{([^}]*)\}\s*from\s*"lucide-react"/g)) {
    for (const part of match[1]!.split(",")) {
      const name = part.trim().split(/\s+as\s+/)[0]!.trim()
      if (name && name !== "type" && !name.startsWith("type ") && name !== "LucideIcon" && name !== "LucideProps") used.add(name)
    }
  }
}
// Icons already in icons.ts stay, so a rerun after React is gone keeps them.
const existing = (() => {
  try {
    return readFileSync(path.join(ROOT, "src/foldkit/ui/icons.ts"), "utf8")
  } catch {
    return ""
  }
})()
for (const match of existing.matchAll(/^export const (\w+) = defineIcon\(/gm)) used.add(match[1]!)

const lines: string[] = []
const imports: string[] = []
for (const name of [...used].sort()) {
  const file = reactNames.get(name)
  if (!file) throw new Error(`lucide-react has no icon ${name}`)
  const vanilla = vanillaByFile.get(file)
  if (!vanilla) throw new Error(`lucide has no icon file ${file}`)
  imports.push(`${vanilla} as ${name}Node`)
  lines.push(`export const ${name} = defineIcon("${file}", ${name}Node)`)
}

writeFileSync(path.join(ROOT, "src/foldkit/ui/icons.ts"), `// Generated by scripts/foldkit/gen-icons.ts: one icon per lucide-react
// icon the client uses. See ./icon.ts for how they render.

import {
${[...new Set(imports)].map((name) => `  ${name},`).join("\n")}
} from "lucide"
import { defineIcon } from "./icon"

${lines.join("\n")}
`)
console.log(`${lines.length} icons`)
